import akshare as ak
import pandas as pd
import datetime
from pathlib import Path
# ================================================================
# 第一次取真实行情数据
# ================================================================
# 和前几天的区别：之前的价格是自己造的（uniform / 随机游走），
# 现在换成从网上下载的真实数据。造的数据能验证算法对不对，
# 真数据才能验证你的算法在现实里站不站得住 —— 两件事都得干。

# 600519 = 贵州茅台，A 股最常被拿来当例子的票

df = ak.stock_zh_a_daily(
    symbol="sh600519",                              # 必须带 sh / sz 前缀
    start_date="20250101",
    end_date=datetime.date.today().isoformat(),
    adjust="qfq",
)

print(df.head(5))
print(df.shape)

# ----------------------------------------------------------------
# adjust（复权）是什么，为什么这里填 "qfq"
# ----------------------------------------------------------------
# 股票分红送股那天，价格会"凭空"掉一截 —— 那不是跌，是除权。
#   不复权 ""    ：照原样给你，图上会出现假跳空，均线全被带歪
#   前复权 "qfq" ：把历史价格统一调整到"今天的口径"，最新的价格不变
#   后复权 "hfq" ：把最新价格调整到"上市那天的口径"
#
# 做技术分析 / 回测一律用 qfq（或 hfq），别用不复权 ——
# 否则你会在除权日看到一根莫名其妙的假大阴线，还以为策略发现了信号。

# ----------------------------------------------------------------
# 存成 CSV 再读回来 —— 为什么要干这一步
# ----------------------------------------------------------------
# 每次跑脚本都联网重取一遍，又慢又看网络脸色（东财那个接口你就见识过了）。
# 正确做法：取一次 → 存本地 → 之后都读本地文件。
# 但得先证明"读回来的"和"刚取的"是同一份东西，
# 否则后面所有分析都建在一份来路不明的数据上。

csv_path = Path(__file__).with_name("sh600519_qfq.csv")
df.to_csv(csv_path, index=False)   # index=False 的作用见下方说明
df2 = pd.read_csv(csv_path)

print("存进去的行数:", len(df))
print("读回来的行数:", len(df2))
print("行数一致    :", len(df) == len(df2))

# ----------------------------------------------------------------
# 三个坑：光看"行数一致"是不够的
# ----------------------------------------------------------------
# 坑 1：index=False 不能省。
#   csv 没有"索引"这个概念。不写 index=False，pandas 会把 RangeIndex
#   （0,1,2...）当成额外一列写进文件，列名是空的。读回来就凭空多出一列
#   "Unnamed: 0" —— 行数照样对得上，你根本不会发现多了一列。

# 坑 2：行数一致 ≠ 内容一致。
#   csv 是纯文本，数字存进去是字符串。读回来 dtype 会变：
#   date 列变成普通字符串（想还原成时间得写 parse_dates=["date"]）。
#   行列都数得对、内容却已经变形，是 csv 最典型的翻车方式。
print("\n原表 dtype     :", dict(df.dtypes.astype(str)))
print("读回来的 dtype :", dict(df2.dtypes.astype(str)))

# 坑 3：这份 csv 是"滑动窗口"的快照，不是一个固定数据集。
#   start_date 写死 20250101，end_date 却是"今天"。
#   所以每天跑一次，窗口右端就往后挪一格 —— 行数和最后一行日期都会变。
#   现在这份的实测：总共 418 行，其中到 2026-09-18 为止只有 417 行，
#   多出来的那 1 行是 2026-09-21。也就是说"418"这个数字本身说明不了什么，
#   它取决于你哪天跑的。
#   拿一个月前的 csv 和今天的数据比总行数，对不上是正常的，别急着怀疑代码。
#   真要对账，就锁定同一段日期区间去比内容，而不是比总行数。
