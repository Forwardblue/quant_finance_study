import akshare as ak
import datetime
# ================================================================
# 第一次取真实行情数据
# ================================================================
# 和前几天的区别：之前的价格是自己造的（uniform / 随机游走），
# 现在换成从网上下载的真实数据。造的数据能验证算法对不对，
# 真数据才能验证你的算法在现实里站不站得住 —— 两件事都得干。

# 600519 = 贵州茅台，A 股最常被拿来当例子的票

df = ak.stock_zh_a_daily(
    symbol="sh600519",                              # 必须带 sh / sz 前缀
    start_date="20250101",
    end_date=datetime.date.today().isoformat(),
    adjust="qfq",
)

print(df.head(5))
print(df.shape)

# ----------------------------------------------------------------
# adjust（复权）是什么，为什么这里填 "qfq"
# ----------------------------------------------------------------
# 股票分红送股那天，价格会"凭空"掉一截 —— 那不是跌，是除权。
#   不复权 ""    ：照原样给你，图上会出现假跳空，均线全被带歪
#   前复权 "qfq" ：把历史价格统一调整到"今天的口径"，最新的价格不变
#   后复权 "hfq" ：把最新价格调整到"上市那天的口径"
#
# 做技术分析 / 回测一律用 qfq（或 hfq），别用不复权 ——
# 否则你会在除权日看到一根莫名其妙的假大阴线，还以为策略发现了信号。
